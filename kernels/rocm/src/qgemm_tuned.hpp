// The row serving a decode call of m rows, or nullptr.
inline const QGemmTuned *qgemm_tuned(const char *arch, int64_t n, int64_t k,
                                     bool vector_scales, int64_t m) {
  const QGemmTuned *serving = nullptr;
  for (const QGemmTuned *t = kQGemmTuned; t->arch != nullptr; ++t) {
    if (__builtin_strcmp(t->arch, arch) != 0 || t->n != n || t->k != k ||
        t->vector_scales != (vector_scales ? 1 : 0) || t->m_max < m) {
      continue;
    }
    if (serving == nullptr || t->m_max < serving->m_max)
      serving = t;
  }
  return serving;
}

// The prefill row (m_max 0: every m of a step that prefills prompt tokens,
// run with split-K off; chosen row-invariant by the tuner) of a shape, or
// nullptr.
inline const QGemmTuned *qgemm_tuned_prefill(const char *arch, int64_t n,
                                             int64_t k, bool vector_scales) {
  for (const QGemmTuned *t = kQGemmTuned; t->arch != nullptr; ++t) {
    if (__builtin_strcmp(t->arch, arch) == 0 && t->n == n && t->k == k &&
        t->vector_scales == (vector_scales ? 1 : 0) && t->m_max == 0) {
      return t;
    }
  }
  return nullptr;
}

