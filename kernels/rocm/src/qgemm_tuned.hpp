// The pinned FP8 GEMM solutions of hipblaslt_fp8 (qgemm.cpp): per card
// architecture, FP8 scale layout, weight shape and decode bucket, the
// hipBLASLt solution the tuner (tools/qgemm_eval.cpp --tune 1) measured
// fastest. hipBLASLt's first heuristic answer for these problems is 1.2-2.4x
// slower than its best at decode sizes (decision "P6: FP8 GEMM — provider
// evaluation (kernel reuse rule)").
//
// A decode row serves m in (previous row's m_max, m_max] of its (arch, n, k,
// scale) in decode steps (turbine_qgemm_desc::prefill 0). A row with m_max 0
// is the shape's prefill solution: every m of a step that prefills prompt
// tokens runs it with split-K off, and the tuner (--tune-prefill 1) picked it
// because its rows are bitwise independent of the call's size and of the
// row's position in it, so a prefix-reused prefill of a prompt's suffix
// computes each row as the whole-prompt prefill does (hipBLASLt's own answers
// are not all like that). A shape without a prefill row runs the first
// heuristic answer for m = 2048 with split-K off and logs
// event=qgemm_prefill_unpinned once. m above every row, a missing row, or a
// row whose solution this hipBLASLt lacks or that rejects the problem runs the
// heuristic's answer (the last case logged
// once per row). Index -1 ("heuristic"): no solution beat the heuristic in that
// bucket. Regenerate with the tuner on the card (GPU 0, under
// scripts/bench-lock.sh) and paste its qgemm_tune rows here.
